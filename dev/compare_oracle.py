#!/usr/bin/env python3
"""Independent oracle for jsonb_stats_compare.

Computes the expected comparison from the textbook definitions with exact
rational arithmetic, NOT from the rearranged z^2 formula used by the spec and
the Rust code, so it checks that algebra as well:

    change_pct      = 100 (S_b - S_a) / |S_a|
    mean_change_pct = 100 (m_b - m_a) / |m_a|
    z               = (m_b - m_a) / sqrt(v_a / n_a + v_b / n_b)

with m = S / n and v the sample variance sum((x - m)^2) / (n - 1), computed
from the values themselves (not from sum_sq). Rounded once to 2 decimals,
half away from zero (for z: the correctly rounded square root).

    cd dev && python3 compare_oracle.py > fixtures/compare_fixture.sql
"""

import sys
from fractions import Fraction
from math import isqrt

from exact_oracle import cents, fmt, jsonb_text, lcg, normalise


def sqrt_cents_signed(q, negative):
    """Correctly rounded 2-decimal sqrt of a Fraction q >= 0, with a sign."""
    x = q * 40000
    mag = (isqrt(x.numerator // x.denominator) + 1) // 2
    return fmt((-mag if negative else mag, 2))


def stats_of(kind, texts):
    vals = [Fraction(*((lambda d: (d[0], 10 ** d[1]))(normalise(kind, t)))) for t in texts]
    return vals


def compare_key(kind, a_texts, b_texts):
    a, b = stats_of(kind, a_texts), stats_of(kind, b_texts)
    na, nb = len(a), len(b)
    sa, sb = sum(a, Fraction(0)), sum(b, Fraction(0))
    out = {"type": kind, "count_a": na, "count_b": nb}
    out["change_pct"] = cents(100 * (sb - sa) / abs(sa)) if sa != 0 else None
    if na > 0 and nb > 0 and sa != 0:
        ma, mb = sa / na, sb / nb
        out["mean_change_pct"] = cents(100 * (mb - ma) / abs(ma))
    else:
        out["mean_change_pct"] = None
    z = None
    if na >= 2 and nb >= 2:
        ma, mb = sa / na, sb / nb
        va = sum((x - ma) ** 2 for x in a) / (na - 1)
        vb = sum((x - mb) ** 2 for x in b) / (nb - 1)
        se2 = va / na + vb / nb
        if se2 > 0:
            d = mb - ma
            z = sqrt_cents_signed(d * d / se2, d < 0)
    out["z"] = z
    return out


# (name, kind, reference values a, subject values b)
CASES = [
    ("peers_vs_subject", "int", [str(i) for i in range(1, 11)], [str(i) for i in range(10, 15)]),
    ("subject_lower", "int", [str(i) for i in range(10, 15)], [str(i) for i in range(1, 11)]),
    ("no_change", "int", ["3", "5", "7"], ["3", "5", "7"]),
    ("single_values", "int", ["0"], ["5"]),
    ("zero_reference_sum", "int", ["-2", "2"], ["1", "3"]),
    ("zero_variance_both", "int", ["4", "4"], ["4", "4"]),
    ("zero_variance_one", "int", ["4", "4"], ["1", "9"]),
    ("negative_mean", "int", ["-10", "-20"], ["-5", "-15", "-25"]),
    ("dec2", "dec2", ["1.50", "2.25", "3"], ["2.10", "2.20"]),
    ("float_small", "float", ["0.1", "0.2", "0.3"], ["0.15", "0.35"]),
    ("float_huge", "float", ["1e15", "3e15"], ["2e15", "2.5e15", "4e15"]),
    ("nat", "nat", ["0", "10", "20"], ["5", "5", "50"]),
    ("i128_overflow", "int", ["9223372036854775807", "-9223372036854775808", "1"],
     ["9223372036854775807", "9223372036854775806"]),
]


def random_cases():
    g = lcg(4711)
    out = []
    for i in range(40):
        na = 1 + next(g) % 30
        nb = 1 + next(g) % 30
        scale = [1, 10, 1000, 10 ** 6][next(g) % 4]
        a = [str(next(g) % (100 * scale) - (5 * scale if i % 5 == 0 else 0)) for _ in range(na)]
        shift = next(g) % 3
        b = [str(next(g) % (100 * scale) + shift * scale) for _ in range(nb)]
        out.append(("random_%02d" % i, "int", a, b))
    return out


def main():
    w = sys.stdout.write
    w("-- GENERATED by dev/compare_oracle.py. Do not edit by hand.\n")
    w("CREATE TEMP TABLE compare_cases(name text PRIMARY KEY, kind text NOT NULL, "
      "a_vals text[] NOT NULL, b_vals text[] NOT NULL, expected jsonb NOT NULL);\n")
    w("INSERT INTO compare_cases VALUES\n")
    lines = []
    for name, kind, a, b in CASES + random_cases():
        arr = lambda v: "ARRAY[" + ", ".join("'%s'" % x for x in v) + "]::text[]"
        lines.append("  ('%s', '%s', %s, %s, '%s')" % (
            name, kind, arr(a), arr(b), jsonb_text(compare_key(kind, a, b))))
    w(",\n".join(lines) + ";\n")


if __name__ == "__main__":
    main()
