#!/usr/bin/env python3
"""Independent oracle for jsonb_stats difference summaries (stats_delta).

Simulates units entering, changing value and leaving a stock over 24 months,
and computes with exact rational arithmetic what
jsonb_stats_delta_to_agg(stock up to month m, changes in month m) must return.
Generates dev/fixtures/delta_fixture.sql:

    python3 dev/delta_oracle.py > dev/fixtures/delta_fixture.sql

Tables:
  delta_units(unit, month_from, month_to, stats)   unit version alive in
      [month_from, month_to) (month_to NULL = still alive)
  delta_expected(month, summary)                   expected summary text
"""

import sys
from fractions import Fraction

from exact_oracle import add, cents, fmt, frac, jsonb_text, lcg, mul, normalise, sqrt_cents

MONTHS = 24
NUM_KEYS = {"emp": "int", "turnover": "dec2", "score": "float", "assets": "nat"}
CAT_KEYS = {"region": "str"}


def canon(kind, d):
    """Canonical scale of a delta sum: int/nat 0, dec2 2, float trimmed."""
    m, s = d
    if kind in ("int", "nat"):
        assert m % 10 ** s == 0
        return (m // 10 ** s, 0)
    if kind == "dec2":
        assert s <= 2
        return (m * 10 ** (2 - s), 2)
    while s > 0 and m % 10 == 0:
        m //= 10
        s -= 1
    return (m, s) if m else (0, 0)


def canon_sq(kind, d):
    if kind == "dec2":
        m, s = d
        assert s <= 4
        return (m * 10 ** (4 - s), 4)
    return canon(kind, d)


def neg(d):
    return (-d[0], d[1])


class NumFlow:
    def __init__(self):
        self.n, self.s, self.q = 0, (0, 0), (0, 0)

    def add(self, v, sign=1):
        self.n += sign
        self.s = add(self.s, v if sign > 0 else neg(v))
        sq = mul(v, v)
        self.q = add(self.q, sq if sign > 0 else neg(sq))


def num_summary(kind, stock, period):
    n = stock.n
    s, q = canon(kind, stock.s), canon_sq(kind, stock.q)
    S1, S2 = frac(s), frac(q)
    N = n * S2 - S1 * S1
    assert n >= 0 and N >= 0
    out = {"type": kind + "_agg", "count": n, "sum": fmt(s), "sum_sq": fmt(q)}
    out["mean"] = cents(S1 / n) if n else None
    out["sum_sq_diff"] = cents(N / n) if n else None
    if n > 1:
        var = N / (n * (n - 1))
        out["variance"] = cents(var)
        out["stddev"] = fmt((sqrt_cents(var), 2))
        if S1 != 0:
            mag = sqrt_cents(10000 * var * n * n / (S1 * S1))
            out["coefficient_of_variation_pct"] = fmt((mag if S1 > 0 else -mag, 2))
        else:
            out["coefficient_of_variation_pct"] = None
    else:
        out["variance"] = out["stddev"] = out["coefficient_of_variation_pct"] = None
    fin, fout = period
    si, so = frac(fin.s), frac(fout.s)  # sum before = S1 - in + out
    s0 = S1 - si + so
    out["in"] = {"count": fin.n, "sum": fmt(canon(kind, fin.s))}
    out["out"] = {"count": fout.n, "sum": fmt(canon(kind, fout.s))}
    out["change_pct"] = cents(100 * (S1 - s0) / abs(s0)) if s0 else None
    return out


def versions():
    """Unit versions: (unit, month_from, month_to or None, {key: value text})."""
    g = lcg(558)
    out = []
    for unit in range(1, 61):
        start = 1 + next(g) % MONTHS if unit > 15 else 1
        end = start + 1 + next(g) % MONTHS
        end = None if end > MONTHS or unit % 4 == 0 else end
        m = start
        while True:
            # a value change after 1..8 months, about half the time
            nxt = m + 1 + next(g) % 8 if next(g) % 2 else None
            stop = end
            if nxt is not None and (end is None or nxt < end) and nxt <= MONTHS:
                stop = nxt
            emp = next(g) % 500 - (5 if unit % 13 == 0 else 0)
            vals = {
                "emp": str(emp),
                "turnover": fmt((next(g) % 10_000_000, 2)) if unit % 3 else str(next(g) % 1000),
                "score": ["0.1", "0.25", "1.50", "2", "1e3", "0.000001"][next(g) % 6],
                "assets": str(next(g) % 100_000),
                "region": ["Oslo", "Bergen", "Tromso"][next(g) % 3],
            }
            out.append((unit, m, stop, vals))
            if stop is None or stop == end:
                break
            m = stop
    return out


def main():
    vs = versions()
    w = sys.stdout.write
    w("-- GENERATED by dev/delta_oracle.py. Do not edit by hand.\n")
    w("CREATE TEMP TABLE delta_units(unit int, month_from int, month_to int, stats jsonb NOT NULL);\n")
    w("INSERT INTO delta_units VALUES\n")
    lines = []
    for unit, a, b, vals in vs:
        stats = {"type": "stats"}
        for k, kind in {**NUM_KEYS, **CAT_KEYS}.items():
            stats[k] = {"type": kind, "value": vals[k] if kind != "str" else vals[k]}
        lines.append("  (%d, %d, %s, '%s')" % (unit, a, "NULL" if b is None else b, jsonb_text(stats)))
    w(",\n".join(lines) + ";\n")
    w("CREATE TEMP TABLE delta_expected(month int PRIMARY KEY, summary jsonb NOT NULL);\n")
    w("INSERT INTO delta_expected VALUES\n")
    lines = []
    for m in range(1, MONTHS + 1):
        out = {"type": "stats_agg"}
        for k, kind in NUM_KEYS.items():
            stock, fin, fout = NumFlow(), NumFlow(), NumFlow()
            for _, a, b, vals in vs:
                v = normalise(kind, vals[k])
                if a <= m and (b is None or m < b):
                    stock.add(v)
                if a == m:
                    fin.add(v)
                if b == m:
                    fout.add(v)
            if stock.n or fin.n or fout.n:
                out[k] = num_summary(kind, stock, (fin, fout))
        for k, kind in CAT_KEYS.items():
            counts, cin, cout = {}, {}, {}
            for _, a, b, vals in vs:
                v = vals[k]
                if a <= m and (b is None or m < b):
                    counts[v] = counts.get(v, 0) + 1
                if a == m:
                    cin[v] = cin.get(v, 0) + 1
                if b == m:
                    cout[v] = cout.get(v, 0) + 1
            if counts or cin or cout:
                out[k] = {"type": kind + "_agg", "counts": counts,
                          "in": {"counts": cin}, "out": {"counts": cout}}
        lines.append("  (%d, '%s')" % (m, jsonb_text(out).replace("'", "''")))
    w(",\n".join(lines) + ";\n")


if __name__ == "__main__":
    main()
